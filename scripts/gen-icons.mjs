// Builds src/components/icons.generated.ts from the Material Symbols SVG package.
// Only the icons listed below are bundled, so the font download is avoided.
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = [
  "keyboard_arrow_down","drag_handle","keyboard_arrow_up","keyboard_double_arrow_up","warning",
  "fiber_new","assignment_ind","construction","hourglass_top","check_circle","replay","block",
  "schedule","error","help","remove","event_repeat","bolt","emergency","report","task_alt","build",
  "check","add","search","call","chat","close","today","person_add","hourglass_bottom",
  "verified","home","confirmation_number","apartment","more_horiz","chevron_left","arrow_forward",
  "calendar_month","groups","engineering","settings","upload_file","photo_camera","attach_file",
  "edit","logout","plumbing","elevator","fire_extinguisher","door_sliding","inbox","content_paste",
  "event","filter_list","person","list_alt","description","open_in_new","info","inventory_2",
];

const dir = "node_modules/@material-symbols/svg-400/rounded/";
const pathOf = (file) => {
  const svg = readFileSync(dir + file, "utf8");
  const m = svg.match(/<path d="([^"]+)"/);
  if (!m) throw new Error("no path in " + file);
  return m[1];
};

const out = {};
for (const n of NAMES) {
  const o = pathOf(`${n}.svg`);
  let f = o;
  try { f = pathOf(`${n}-fill.svg`); } catch {}
  out[n] = { o, f };
}
writeFileSync(
  "src/components/icons.generated.ts",
  "// Generated by scripts/gen-icons.mjs. Do not edit.\nexport const ICONS: Record<string, { o: string; f: string }> = " +
    JSON.stringify(out) + ";\n",
);
console.log("icons:", Object.keys(out).length);
